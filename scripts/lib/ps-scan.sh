#!/bin/bash
# 共用谓词：判"命令行里带某段图案的那件事**真在跑**"，并豁免调用者自己这一树。
# ============================================================================
#
# 🔴 为什么要有一份共用的，而不是每个看守自己 `pgrep -f`：
#    这条线上已经有三处要做同一个判断（B 看守让路给 H 的 e2e、H 看守让路给 C 链与四端重装、
#    验证台量基线），而它们踩的是**同一个坑的两个面**：
#      面一（图案自己）：`grep -c 'needle'` 的进程 argv 里就带着 needle，`ps` 拍快照时它自己活着
#                        ⇒ 现场明明空，基线数出 1（本仓 §7 同族：`grep -c` 在缺文件时一个字都不打印）。
#      面二（调用链）：把装置**投起来的那条命令行**里带着 needle 时，它是装置的祖先，
#                        会被当成"那件事在跑"。M4 变异实测：B 看守因此误判 H 在跑而白让 1800s。
#    面一靠 `[.]` / `[-]` 这种"写法不等于读法"的图案挡；面二只能靠**按 pid 豁免自己这一树**挡
#    （同另一条规矩：查外部锁要排除自己+祖先+后代）。这里把面二做成一处实现，三处共用。
#
# 约定：
#   - 只往 stdout 打印**不在本进程祖先链上**的匹配 pid，一行一枚；没匹配就什么都不打
#     （"取不到"与"没有"都必须能区分，所以调用方要数枚数，见 `ht_ps_has ... | wc -l`）。
#   - 图案按 `pgrep -f` 的 ERE 解释；调用方仍应把图案写成 `x[.]?y` 这种**自匹配不成立**的形状。
#   - 退出码恒 0（这是一次读数，不是判断）；图案为空 ⇒ 用法错，退 2。
#
# 用法（bash 3.2）：
#   . scripts/lib/ps-scan.sh
#   PID=$(ht_ps_has 'scripts/[.]?reinstall-all' | head -1)

ht_ps_has() {
  local _re="$1" _p _skip=" $$" _q
  if [ -z "$_re" ]; then
    echo "ht_ps_has: 图案为空（用法: ht_ps_has '<pgrep -f 正则>'）" >&2
    return 2
  fi
  # 先把"我自己 + 全部祖先"攒成一张豁免表；到 init 或空为止（ppid 取不到就停，不猜）。
  _p=$$
  while [ -n "$_p" ] && [ "$_p" != "1" ] && [ "$_p" != "0" ]; do
    _p=$(ps -o ppid= -p "$_p" 2>/dev/null | tr -d ' \t')
    [ -n "$_p" ] && _skip="$_skip $_p"
  done
  # pgrep 不含它自己，但**含**投它起来的那条命令行 ⇒ 豁免表必须在这之后逐枚过一遍。
  pgrep -f "$_re" 2>/dev/null | while IFS= read -r _q; do
    [ -z "$_q" ] && continue
    case "$_skip " in *" $_q "*) continue ;; esac
    printf '%s\n' "$_q"
  done
  return 0
}
