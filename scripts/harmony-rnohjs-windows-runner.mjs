function run(line, { cwd, timeout = 0 } = {}) {
  const r = spawnSync(process.env.ComSpec || 'cmd.exe', ['/d', '/s', '/c', line], {
    cwd,
    env: childEnv,
    encoding: 'utf8',
    timeout,
    maxBuffer: 128 * 1024 * 1024,
    windowsVerbatimArguments: true,
  });
  if (r.error) return { status: 1, out: `${r.stdout ?? ''}${r.stderr ?? ''}${r.error.message}` };
  return { status: r.status ?? 1, out: `${r.stdout ?? ''}${r.stderr ?? ''}` };
}

function readZipEntries(file) {
  const buf = fs.readFileSync(file);
  let eocd = -1;
  for (let i = buf.length - 22; i >= Math.max(0, buf.length - 66000); i -= 1) {
    if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error('不是 zip：找不到 EOCD');
  const count = buf.readUInt16LE(eocd + 10);
  let p = buf.readUInt32LE(eocd + 16);
  const entries = [];
  for (let i = 0; i < count; i += 1) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error('中央目录损坏');
    const size = buf.readUInt32LE(p + 24);
    const nameLen = buf.readUInt16LE(p + 28);
    const extraLen = buf.readUInt16LE(p + 30);
    const commentLen = buf.readUInt16LE(p + 32);
    entries.push({ name: buf.subarray(p + 46, p + 46 + nameLen).toString('utf8'), size });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return entries;
}

/*
 * 🔴 **不要跳过 `build`**：产出的 `.hap` 就在 `entry/build/default/outputs/…` 底下。
 *    第一版这里跳了 `build`（想着"构建产物别进去翻"），于是 release 明明退出 0，
 *    却被判成"没有产出任何 .hap" —— 一条假红，看起来像构建没出包。
 *    要跳的只有依赖目录。
 */
function walk(dir, hit, out = [], skip = new Set(['oh_modules', 'node_modules'])) {
  if (!fs.existsSync(dir)) return out;
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, d.name);
    if (d.isDirectory()) {
      if (skip.has(d.name)) continue;
      walk(full, hit, out, skip);
    } else if (hit(d.name)) out.push(full);
  }
  return out;
}

const read = (p) => fs.readFileSync(p, 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); fs.writeFileSync(p, s); };

