const codegenHeader = path.join(HARMONY, 'entry', 'src', 'main', 'cpp', 'generated', 'RNOHGeneratedPackage.h');
if (fs.existsSync(codegenHeader)) ok('codegen 产物：RNOHGeneratedPackage.h');
