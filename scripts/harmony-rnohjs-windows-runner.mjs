/* ── 4. 真 bundle（Metro → Hermes 字节码）───────────────── */

step('4. bundle-harmony（真 Hermes 字节码）');
/* 🔴 hermesc 不在 `react-native/sdks/hermesc/`（bundle-harmony 默认去那找，会报
 *    "Couldn't find hermesc"），它由 `hermes-compiler` 包提供 ⇒ 必须 --hermesc-dir。 */
const HBC = path.join(HARMONY, 'entry', 'src', 'main', 'resources', 'rawfile', 'hermes_bundle.hbc');
fs.mkdirSync(path.dirname(HBC), { recursive: true });
const bundle = run(
  `node_modules\\.bin\\react-native.cmd bundle-harmony --entry-file index.js --bundle-output "${HBC}" `
  + `--assets-dest "${path.join(HARMONY, 'entry', 'src', 'main', 'resources', 'rawfile', 'assets')}" `
  + '--js-engine hermes --dev false --hermesc-dir node_modules\\hermes-compiler\\hermesc',
  { cwd: PROJ, timeout: 30 * 60 * 1000 },
);
if (bundle.status === 0) ok('bundle-harmony 退出码 0');
else {
  bad('bundle-harmony 失败');
  info(bundle.out.split('\n').filter((l) => /error|Couldn't/i.test(l)).slice(0, 6).join('\n'));
}

if (fs.existsSync(HBC)) {
  /* 扩展名可以随便起，**魔数**不行 —— 验它，别验文件名。 */
  const head = fs.readFileSync(HBC).subarray(0, 8);
  const magic = head.length === 8 ? `0x${head.readBigUInt64LE(0).toString(16).toUpperCase()}` : 'short';
  const size = fs.statSync(HBC).size;
  if (magic === '0x1F1903C103BC1FC6') ok(`Hermes 魔数正确（${size} 字节）`);
  else bad(`不是 Hermes 字节码（魔数 ${magic}）—— 可能是改了扩展名的 JS`);
} else {
  bad('没有产出 hermes_bundle.hbc');
}

/* ── 5. release HAP：bundle 与原生库都要进包 ────────────── */

step('5. release HAP：验证 bundle 与原生库真的进包');
const releaseLog = run(`${HVIGORW} assembleHap --mode module -p product=default -p buildMode=release --no-daemon`,
  { cwd: HARMONY, timeout: 90 * 60 * 1000 });
if (releaseLog.status === 0) ok('release 构建退出码 0');
else {
  bad('release 构建失败');
  info(releaseLog.out.split('\n').filter((l) => /ERROR|error:/.test(l)).slice(0, 8).join('\n'));
}

const haps = walk(HARMONY, (n) => n.toLowerCase().endsWith('.hap'));
if (haps.length === 0) {
  bad('没有产出任何 .hap');
  console.log(`\n通过 ${PASS}，失败 ${FAIL}`);
  process.exit(1);
}
/* release 优先：文件名里带 release 的那份；否则取最大的那份。 */
const HAP = haps.sort((a, b) => fs.statSync(b).size - fs.statSync(a).size)[0];
const hapSize = fs.statSync(HAP).size;
ok(`产出 ${path.basename(HAP)}（${hapSize} bytes）`);

/* 🔴 "成品量级"是判据的一部分：entry 模块壳是 400 KB 量级，带原生库的成品是十 MB 量级。
 *    退出码 0 与体积量级是两件事 —— 后者才说明原生侧真的进包了。 */
if (hapSize > 20 * 1024 * 1024) ok(`体积在成品量级（> 20 MiB）`);
else bad(`体积只有 ${hapSize} bytes —— 这是壳的量级，原生库或 bundle 没进包`);

let entries = [];
try { entries = readZipEntries(HAP); } catch (e) { bad(`读不了 HAP 的条目表：${e.message}`); }
const findEntry = (needle) => entries.find((e) => e.name.endsWith(needle));

const hbc = findEntry('rawfile/hermes_bundle.hbc');
if (hbc !== undefined) ok(`HAP 内含 hermes_bundle.hbc（${hbc.size} 字节，自包含，不依赖 Metro）`);
else bad('HAP 内没有 hermes_bundle.hbc —— 装到设备上会连不上 Metro 白屏');

for (const lib of ['librnoh_core.so', 'librnoh_app.so', 'libreactnative.so']) {
  const e = findEntry(lib);
  if (e !== undefined) ok(`HAP 内含 ${lib}（${e.size} 字节）`);
  else bad(`HAP 缺 ${lib}`);
}

console.log('\n==== 汇总 ====');
console.log(`通过 ${PASS} 项，失败 ${FAIL} 项`);
console.log(`HAP ${HAP}`);
process.exit(FAIL === 0 ? 0 : 1);
