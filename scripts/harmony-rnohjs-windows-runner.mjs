#!/usr/bin/env node
/**
 * 鸿蒙 · **JS 侧全链路（零桩）**探针 —— 在 `windows-pc` 上执行的那一半。
 *
 * 由 `scripts/build-harmony-rnohjs-windows.mjs` 推过去、用 DevEco 自带的 node 跑。
 *
 * 这是 `scripts/verify-harmony-rnoh-js.sh`（macOS 版，写死
 * `/Applications/DevEco-Studio.app/Contents` 且依赖 `python3`）的 Windows 移植。
 *
 * ## 它与 `harmony-rnoh-windows-runner.mjs` 的分工
 *
 * | 脚本 | 顶替了什么 | 回答什么 |
 * |---|---|---|
 * | `harmony-rnoh-windows-runner.mjs` | codegen/autolinking **用桩** | RNOH 的 C++ 能不能编译并进包 |
 * | **本脚本** | **零桩**：真 `@rnoh/hvigor-plugin` codegen、真 autolinking、真 Metro→Hermes | 整条链（含 JS bundle）能不能出**自包含的 release HAP** |
 *
 * ## 判据（每条都能红）
 *
 * 1. Node 版本 ≥ 20.12（RN 0.84 CLI 要 `util.styleText`）—— DevEco 自带的就是 v24，这条在
 *    Windows 上是**顺的**；在 macOS 上 DevEco 带的是 18，反向红过。
 * 2. codegen/autolinking 的产物里写着 `generated by RNOH autolinking`（**桩写不出这句**）。
 * 3. `hermes_bundle.hbc` 的**魔数**是 `0x1F1903C103BC1FC6`（不是改了扩展名的 JS）。
 * 4. release HAP 里同时有 `hermes_bundle.hbc` 与三个关键 `.so`，且体积在成品量级。
 *
 * 🔴 **不验运行**：缺模拟器镜像 + 签名，产物是 unsigned。
 *    本脚本**不对「RN 应用在鸿蒙上跑得起来」下任何结论**。
 *
 * ## 输出契约
 *
 * 每行一条判据，前缀固定 `OK  ` / `BAD ` / `INFO`。驱动侧按前缀计数，不猜退出码。
 */
