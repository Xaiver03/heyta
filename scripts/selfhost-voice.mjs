/**
 * 「自托管豁免区」的唯一判据 —— 两套门禁共用
 * =========================================
 *
 * 规则来自产品负责人 2026-10-01 的明确指令：
 * **文档中心绝对不能放开发相关的东西；唯一例外是自托管那块 ——
 * 自托管说明就是写给动手的人看的，可以详细到开发者级。**
 *
 * 🔴 为什么这个判断只能有一份
 *
 * 同一条豁免有**两个观测面**：
 *
 *   - `scripts/check-docs-voice.mjs` 扫**词条表**（按 key 判豁免），
 *   - `apps/landing/tests/public-copy-register.spec.tsx` 扫**渲染出来的页面文本**
 *     （按页面判豁免）。
 *
 * 这个分裂已经在 2026-10-01 真实咬过一次：前者按新裁定把自托管篇整篇豁免、
 * 并把该篇扩到 11 节开发者级内容，后者（前一天立的闸）不知道有豁免这回事，
 * 于是 `selfhost / zh-CN`、`selfhost / en` 两页**当场变红**，而 `pnpm check`
 * 带着它一起红 —— 症状是"内容合规门禁在拦一份被裁定为合规的内容"。
 *
 * 把判据抄两遍的下一站就是本仓库已经吃过的那类事故（AGENTS.md §3.2 里那条
 * "失败判据被抄了三遍、三遍都漏了同一档"）：**改一处、另一处过期，而过期那处
 * 看起来仍在执法**。所以这里只有一份，两个门禁都从这里取。
 *
 * ⚠️ 两个观测面的粒度不同，所以是**两个形状**，不是一个函数：
 * key 前缀（词条表）与页面 id（渲染文本）。它们圈的是同一块内容，
 * 将来扩大豁免区时**两处必须一起动**，而它们都住在本文件里，动一处就会在
 * 另一处的注释里留下线索。
 */

/**
 * 词条表侧：自托管相关 key 的豁免判据。
 *
 * 为什么平台页与集成页的自托管段也在内：它们是同一个"给动手的人的说明"，
 * 只是挂在不同的页面上（判据按内容划，不按页面划）。
 */
export function isSelfhostCopyKey(key) {
  return (
    key.startsWith('site.docs.selfhost.') ||
    key === 'site.platforms.selfhost.body' ||
    key === 'site.integrations.selfhost.body'
  );
}

/**
 * 渲染文本侧：整页豁免的页面 id。
 *
 * 🔴 只放**自托管这一篇文章页**，不放平台页与集成页 —— 后两者的自托管段
 * 只是整页里的一小节，那一小节周围全是营销语言，整页豁免会把"访客读到的
 * 产品承诺"一并放行。这两页的自托管文案因此仍然受**公页语域**约束，
 * 这是**刻意比词条闸更严**的：漏在页面上的命令与机制说法，用户读到的概率
 * 比漏在自托管专篇里高得多。
 */
export const SELFHOST_EXEMPT_PAGE_IDS = Object.freeze(['selfhost']);
