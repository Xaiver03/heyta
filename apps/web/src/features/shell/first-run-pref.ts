/**
 * 首启引导「已经看过」的**设备本地**标记。
 * ==========================================
 *
 * 与 `detail-pane-pref.ts` / `sort-pref.ts` / `modules.ts` 同一条推理：
 * "这一台设备上的这个人有没有被引导过"是**界面状态**，不是用户数据 ——
 * 不进 op-log（AGENTS §3.4：op-log 只装用户意图），也不跨设备同步。
 *
 * ## 为什么是"已看过"而不是"已完成"
 *
 * 引导里没有任何"必须做完"的动作：点一条示例、按回车、或者直接点「先自己写」，
 * 三件事都算看过了。**只有"没看过"和"看过"两态**，这样它永远不可能把用户卡在
 * 一个没做完的流程里 —— 那正是多步巡览最坏的那种失败（`uxpatternsguide.com`
 * 把它列为 weak implementation：六张幻灯片 + 每张点 Next + 最后落在空 dashboard）。
 *
 * ## 三条纪律（照抄那几份）
 *
 * 1. **永不抛** —— 隐私模式下访问 `localStorage` 会抛，读失败退默认、写失败静默；
 * 2. 非法值退回默认档（手改存储 / 旧版本残留），不让界面进入说不清的状态；
 * 3. 词表只有一份：调用点不许各自比字符串。
 *
 * ⚠️ **默认是"没看过"**：出厂状态就是新用户，引导该出现。老用户第一次升级到
 * 这一版时会看到一次 —— 这是**可接受的一次性代价**（它可一键关掉，且不挡操作）。
 * 如果哪天这个代价不可接受，正确做法是加一个"版本号 + 只在首装出现"的字段，
 * 而不是把默认翻成"看过"（那会让真新用户永远看不到）。
 */

const KEY = 'heyta.firstRunSeen';

/** 读：真 = 已经看过（不再出现）。任何异常都当"没看过"之外的安全值。 */
export function loadFirstRunSeen(): boolean {
  try {
    return localStorage.getItem(KEY) === '1';
  } catch {
    // 读不到时**当作没看过**是错的（隐私模式下会每次启动都弹），
    // 所以反过来：读不到就当"看过"，宁可少引导一次也不打扰。
    return true;
  }
}

/** 写：标记为已看过。写失败不影响本次（这次已经收起，只是下次启动会再出现一次）。 */
export function markFirstRunSeen(): void {
  try {
    localStorage.setItem(KEY, '1');
  } catch {
    // 隐私模式：静默。
  }
}
