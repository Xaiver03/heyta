/**
 * 横向拖拽换段的**判据**（纯函数，不碰 DOM）
 * ==========================================
 *
 * 产品负责人 2026-10-03 给滴答日视图截图时说的第二句：
 * **"你的鼠标在这里左右滑动，就是左右拖拽滑动。那就是上一天和下一天的切换。"**
 *
 * ─────────────────────────────────────────────────────────────────────────
 * 🔴 判据只有"位移够不够、是不是横的"，**没有"走多远"**
 *
 * 一次拖拽 = **一段**；走多远由 `@heyta/ui` 的 `stepCalendarCursor(view, …)` 决定
 * （日档一天、周档一周、月档一月）。这里如果自己写 `addDays(dx/200)`，
 * 就成了"手势一套算法、箭头一套算法"——本仓为这个形状记过整页账。
 * 所以本文件**不 import 任何日期算术**，只回 `-1 / 0 / +1`。
 *
 * ⚠️ 方向写反**不会有任何报错**：界面照样换天，只是每次拖反。
 *    判据必须钉"往左拖 = 往后一天"，不能只钉"日期变了"（与 `wheel-month.ts` 同一条）。
 *
 * ## 为什么阈值是 44
 *
 * **不是随手写的数**：`44` 是设计 token `touch-target.min` 的值（`tokens.css`
 * 的 `--ht-touch-target-min: 2.75rem /* 44px *\/`），含义是"一颗可点目标的边长"。
 * 用它当"这算拖拽还是算误碰"的分界有明确的物理意义：
 *
 * · 一次**点击**里指针的合理抖动远小于一颗按钮（几 px），必须**不**被当成拖拽；
 * ·  pointer 移动了**整整一颗目标**的宽度，在任何光标习惯里都不是误碰。
 *
 * ⚠️ 这里没有 `import` token：手势阈值是**交互参数**，不是视觉尺度，
 *    而 `check:design` 管的是样式里的裸值。但"这个数从哪来"必须有答案，就写在上面。
 *    真要把 token 注进来，得先回答"暗色主题会不会改手势阈值"——不会。
 */

/** 判定"这是一次拖拽，不是一次误碰"所需的横向位移（px）。理由见文件头。 */
export const DRAG_MIN_PX = 44;

/**
 * 一次拖拽 → 走几段。
 *
 * @param dx 水平位移（右为正，`pointerup.clientX - pointerdown.clientX`）
 * @param dy 垂直位移（下为正）—— 只用来判断**这是不是一次横向往复**
 * @returns `-1` 往过去 / `0` 不算拖拽（把事件让给点击与滚页）/ `+1` 往未来
 */
export function readDragSegments(dx: number, dy: number): -1 | 0 | 1 {
  // ① 够不够远。不到一颗目标宽度的移动 = 点击的抖动，整条让出去（下面还要放行 click）。
  if (Math.abs(dx) < DRAG_MIN_PX) return 0;
  // ② 以竖向为主 = 用户在**滚这一屏**（日档那根 24 小时的轴比视口高）。
  //    这时候横移只是"斜着往下拖"，改天会把滚动毁掉。
  if (Math.abs(dx) <= Math.abs(dy)) return 0;
  // ③ 往左拖 = 把当前这页推走 = **未来**（与轮播、与滴答那条手势同一读法）。
  return dx < 0 ? 1 : -1;
}
