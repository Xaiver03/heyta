    // ── 解析 ──────────────────────────────────────────────────────────────────

    private static MetaType? ElementClrType(XElement element, MetadataIndex meta) =>
        ResolveByTag(element.Name.LocalName, element, meta);

    private static MetaType? ResolveByTag(string tag, XElement context, MetadataIndex meta)
    {
        foreach (var candidate in CandidatesFor(tag, context, meta))
        {
            var type = meta.Find(candidate);
            if (type is not null)
            {
                return type;
            }
        }

        return null;
    }

    private static IEnumerable<string> CandidatesFor(string tag, XElement context, MetadataIndex meta)
    {
        var ns = context.Name.NamespaceName;

        if (ns == PresentationNs)
        {
            // 默认 xmlns = 那一整套 `Microsoft.UI.Xaml*` 命名空间（不是只有 Controls）。
            // 顺序由 MetadataIndex 给（Controls 优先），候选**来自元数据**而不是手写清单。
            foreach (var fullName in meta.XamlTypeCandidates(tag))
            {
                yield return fullName;
            }

            yield break;
        }

        if (ns.StartsWith(UsingPrefix, StringComparison.Ordinal))
        {
            yield return ns[UsingPrefix.Length..] + "." + tag;
        }
    }

    private static MetaType? ResolveXamlTypeName(string value, XElement context, MetadataIndex meta)
    {
        var colon = value.IndexOf(':');
        if (colon < 0)
        {
            return meta.Find(value);
        }

        var prefix = value[..colon];
        var rest = value[(colon + 1)..];
        var ns = LookupXmlns(context, prefix);

        if (ns is null)
        {
            return null;
        }

        if (ns.StartsWith(UsingPrefix, StringComparison.Ordinal))
        {
            return meta.Find(ns[UsingPrefix.Length..] + "." + rest);
        }

        if (ns == PresentationNs)
        {
            foreach (var fullName in meta.XamlTypeCandidates(rest))
            {
                var type = meta.Find(fullName);
                if (type is not null)
                {
                    return type;
                }
            }
        }

        return null;
    }

    private static string? LookupXmlns(XElement context, string prefix)
    {
        for (var element = context; element is not null; element = element.Parent)
        {
            foreach (var attribute in element.Attributes())
            {
                if (!attribute.IsNamespaceDeclaration)
                {
                    continue;
                }

                var declaredPrefix = attribute.Name.NamespaceName == "http://www.w3.org/2000/xmlns/"
                    ? attribute.Name.LocalName
                    : string.Empty;

                if (declaredPrefix == prefix)
                {
                    return attribute.Value;
                }
            }
        }

        return null;
    }

    private static MetaType? DataTypeInScope(XElement element, MetadataIndex meta)
    {
        for (var current = element; current is not null; current = current.Parent)
        {
            var dataTypeAttribute = current.Attributes()
                .FirstOrDefault(a => a.Name.NamespaceName == XamlDirectNs && a.Name.LocalName == "DataType");

            if (dataTypeAttribute is not null)
            {
                // 解析失败留给 x:DataType 自己的那条判据报，这里只回 null
                return ResolveXamlTypeName(dataTypeAttribute.Value, current, meta);
            }
        }

        return null;
    }

    private static string? ExtractBindPath(string value)
    {
        var inner = value.Trim();
        if (inner.StartsWith('{'))
        {
            inner = inner[1..];
        }

        if (inner.EndsWith('}'))
        {
            inner = inner[..^1];
        }

        var space = inner.IndexOf(' ');
        if (space < 0)
        {
            return null;
        }

        var arguments = inner[(space + 1)..];
        var first = (SplitTopLevel(arguments).FirstOrDefault() ?? string.Empty).Trim();

        if (first.StartsWith("Path=", StringComparison.Ordinal))
        {
            first = first["Path=".Length..].Trim();
        }

        return first.Length == 0 ? null : first;
    }

    private static IEnumerable<string> SplitTopLevel(string text)
    {
        var depth = 0;
        var quote = '\0';
        var start = 0;

        for (var i = 0; i < text.Length; i++)
        {
            var c = text[i];

            if (quote != '\0')
            {
                if (c == quote)
                {
                    quote = '\0';
                }

                continue;
            }

            switch (c)
            {
                case '"':
                case '\'':
                    quote = c;
                    break;
                case '{':
                case '(':
                case '[':
                    depth++;
                    break;
                case '}':
                case ')':
                case ']':
                    depth--;
                    break;
                case ',' when depth == 0:
                    yield return text[start..i];
                    start = i + 1;
                    break;
            }
        }

        if (start < text.Length)
        {
            yield return text[start..];
        }
    }

