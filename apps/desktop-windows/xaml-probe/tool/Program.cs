    private sealed class XamlDoc
    {
        public required string Path { get; init; }

        public required string Relative { get; init; }

        public required XDocument Xml { get; init; }

        public required string ClassFullName { get; init; }

        public required string CodeBehindPath { get; init; }

        public string ClassName => ClassFullName.Split('.')[^1];

        public string ClassNamespace => ClassFullName.Contains('.')
            ? ClassFullName[..ClassFullName.LastIndexOf('.')]
            : string.Empty;

        public XElement Root => Xml.Root!;
    }

    private static List<XamlDoc> LoadDocs(string xamlDir)
    {
        var docs = new List<XamlDoc>();

        foreach (var path in Directory.GetFiles(xamlDir, "*.xaml", SearchOption.TopDirectoryOnly).OrderBy(p => p, StringComparer.Ordinal))
        {
            XDocument xml;
            try
            {
                xml = XDocument.Load(path, LoadOptions.SetLineInfo);
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine($"❌ {Path.GetFileName(path)}: XML 不良构 —— {ex.Message}");
                continue;
            }

            var classAttribute = xml.Root?.Attributes()
                .FirstOrDefault(a => a.Name.NamespaceName == XamlDirectNs && a.Name.LocalName == "Class");

            if (classAttribute is null)
            {
                Console.Error.WriteLine($"❌ {Path.GetFileName(path)}: 根元素上没有 x:Class（XAML 编译器会拒）");
                continue;
            }

            docs.Add(new XamlDoc
            {
                Path = path,
                Relative = Path.GetFileName(path),
                Xml = xml,
                ClassFullName = classAttribute.Value,
                CodeBehindPath = path + ".cs",
            });
        }

        return docs;
    }

    private static HashSet<string> LoadResourceKeys(string tokensPath)
    {
        if (!File.Exists(tokensPath))
        {
            throw new InvalidOperationException($"tokens 生成物不存在：{tokensPath}（先跑 token 生成脚本）");
        }

        var keys = new HashSet<string>(StringComparer.Ordinal);
        var xml = XDocument.Load(tokensPath);

        foreach (var element in xml.Descendants())
        {
            var key = element.Attributes()
                .FirstOrDefault(a => a.Name.NamespaceName == XamlDirectNs && a.Name.LocalName == "Key");

            if (key is not null)
            {
                keys.Add(key.Value);
            }
        }

        return keys;
    }

    private readonly struct ClassDeclaration
    {
        public required string Modifiers { get; init; }

        public required bool IsPartial { get; init; }

        public required string? BaseType { get; init; }

        public required bool HasInitializeComponent { get; init; }
    }

    private static ClassDeclaration? ReadClassDeclaration(XamlDoc doc)
    {
        if (!File.Exists(doc.CodeBehindPath))
        {
            return null;
        }

        var source = File.ReadAllText(doc.CodeBehindPath);
        var match = Regex.Match(
            source,
            $@"(?m)^\s*((?:(?:public|internal|sealed|abstract|static|unsafe|new)\s+|partial\s+)*)class\s+{Regex.Escape(doc.ClassName)}\s*(?::\s*([A-Za-z_][\w\.<>]*))?");

        if (!match.Success)
        {
            return null;
        }

        var modifiers = match.Groups[1].Value;
        var baseType = match.Groups[2].Success && match.Groups[2].Value.Length > 0
            ? match.Groups[2].Value.Split('.').Last().Split('<')[0]
            : null;

        return new ClassDeclaration
        {
            Modifiers = modifiers,
            IsPartial = Regex.IsMatch(modifiers, @"\bpartial\b"),
            BaseType = baseType,
            HasInitializeComponent = Regex.IsMatch(source, @"\bvoid\s+InitializeComponent\s*\("),
        };
    }

    private static IEnumerable<(string Name, XElement Element)> NamedElements(XamlDoc doc)
    {
        foreach (var element in doc.Root.DescendantsAndSelf())
        {
            var name = element.Attributes()
                .FirstOrDefault(a => a.Name.NamespaceName == XamlDirectNs && a.Name.LocalName == "Name");

            if (name is not null)
            {
                yield return (name.Value, element);
            }
        }
    }

