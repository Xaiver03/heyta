    private sealed class MetaType
    {
        private readonly MetadataIndex _index;
        private readonly MetadataReader _reader;
        private readonly TypeDefinitionHandle _handle;

        public MetaType(MetadataIndex index, MetadataReader reader, TypeDefinitionHandle handle, string fullName)
        {
            _index = index;
            _reader = reader;
            _handle = handle;
            FullName = fullName;

            var dot = fullName.LastIndexOf('.');
            Name = dot < 0 ? fullName : fullName[(dot + 1)..];
        }

        public string FullName { get; }

        public string Name { get; }

        public bool IsValueType
        {
            get
            {
                var baseType = _index.BaseTypeName(_reader, _handle);
                return baseType is "System.ValueType" or "System.Enum";
            }
        }

        /// <summary>
        /// 自己 + 整条基类链。**必须走链**：XAML 里的 `Background` / `Opacity` / `Width` / `Content` /
        /// `Style` / `ItemTemplate` 全都不在 `Button`、`TextBlock` 自己身上，而在
        /// `Control` / `FrameworkElement` / `UIElement` / `ItemsControl` 上。
        /// 只看自己会把这些**正确的**写法判成红 —— 那是最坏的一种判据：它逼人关掉门禁。
        /// </summary>
        private IEnumerable<(MetadataReader Reader, TypeDefinitionHandle Handle)> SelfAndBases()
        {
            var reader = _reader;
            var handle = _handle;

            for (var depth = 0; depth < 16; depth++)
            {
                yield return (reader, handle);

                EntityHandle baseType;
                try
                {
                    baseType = reader.GetTypeDefinition(handle).BaseType;
                }
                catch
                {
                    yield break;
                }

                if (baseType.IsNil)
                {
                    yield break;
                }

                if (baseType.Kind == HandleKind.TypeDefinition)
                {
                    handle = (TypeDefinitionHandle)baseType;
                    continue;
                }

                if (baseType.Kind == HandleKind.TypeReference)
                {
                    var located = _index.Locate(_index.FullNameOf(reader, baseType));
                    if (located.Reader is null)
                    {
                        yield break;
                    }

                    reader = located.Reader;
                    handle = located.Handle!.Value;
                    continue;
                }

                yield break;
            }
        }

        public MetaProperty? FindProperty(string name)
        {
            foreach (var (reader, handle) in SelfAndBases())
            {
                foreach (var propertyHandle in reader.GetTypeDefinition(handle).GetProperties())
                {
                    var definition = reader.GetPropertyDefinition(propertyHandle);
                    if (reader.GetString(definition.Name) != name)
                    {
                        continue;
                    }

                    var signature = definition.DecodeSignature(_index.TypeProvider, (object?)null);
                    return new MetaProperty { Name = name, TypeName = signature.ReturnType };
                }
            }

            return null;
        }

        public bool HasEvent(string name)
        {
            foreach (var (reader, handle) in SelfAndBases())
            {
                foreach (var eventHandle in reader.GetTypeDefinition(handle).GetEvents())
                {
                    if (reader.GetString(reader.GetEventDefinition(eventHandle).Name) == name)
                    {
                        return true;
                    }
                }
            }

            return false;
        }

        public MetaMethod? FindStaticMethod(string name, int parameterCount)
        {
            foreach (var (reader, handle) in SelfAndBases())
            {
                foreach (var methodHandle in reader.GetTypeDefinition(handle).GetMethods())
                {
                    var definition = reader.GetMethodDefinition(methodHandle);
                    if (reader.GetString(definition.Name) != name)
                    {
                        continue;
                    }

                    if ((definition.Attributes & MethodAttributes.Static) == 0)
                    {
                        continue;
                    }

                    if (definition.GetParameters().Count != parameterCount)
                    {
                        continue;
                    }

                    var signature = definition.DecodeSignature(_index.TypeProvider, (object?)null);
                    return new MetaMethod { Name = name, ParameterTypes = signature.ParameterTypes };
                }
            }

            return null;
        }
    }

    private sealed class MetadataIndex : IDisposable
    {
        private readonly List<(MetadataReader Reader, string Path)> _readers = new();
        private readonly List<PEReader> _peReaders = new();
        private readonly Dictionary<string, MetaType?> _cache = new(StringComparer.Ordinal);
        private readonly HashSet<string> _warned = new(StringComparer.Ordinal);

        private MetadataIndex() => TypeProvider = new NameTypeProvider(this);

        public NameTypeProvider TypeProvider { get; }

        public static MetadataIndex FromCompileDir(string compileDir)
        {
            // 🔴 输入不是写死的路径：compile 工程把它**真的看到的** @(ReferencePath) 落在这里。
            var refsFile = Path.Combine(compileDir, "obj", "probe-refs.txt");
            var outFile = Path.Combine(compileDir, "obj", "probe-out.txt");

            if (!File.Exists(refsFile))
            {
                throw new InvalidOperationException(
                    $"缺少元数据输入 {refsFile} —— 先跑 `dotnet build {compileDir} -t:ResolveAssemblyReferences`");
            }

            var index = new MetadataIndex();
            var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

            void Add(string path)
            {
                if (path.Length == 0
                    || !path.EndsWith(".dll", StringComparison.OrdinalIgnoreCase)
                    || !File.Exists(path)
                    || !seen.Add(Path.GetFileName(path)))
                {
                    return;
                }

                try
                {
                    var stream = File.OpenRead(path);
                    var pe = new PEReader(stream);

                    if (!pe.HasMetadata)
                    {
                        pe.Dispose();
                        stream.Dispose();
                        return;
                    }

                    index._peReaders.Add(pe);
                    index._readers.Add((pe.GetMetadataReader(), path));
                }
                catch
                {
                    // 原生 / WinMD / 依赖缺口：读不了就跳过。它不会让判据变绿 ——
                    // 需要用到它的时候 Find() 回 null 并判红。
                }
            }

            foreach (var line in File.ReadAllLines(refsFile))
            {
                Add(line.Trim());
            }

            if (File.Exists(outFile))
            {
                Add(File.ReadAllText(outFile).Trim());
            }

            return index;
        }

        private Dictionary<string, List<string>>? _xamlTagIndex;

        /// <summary>
        /// 默认 XAML xmlns 覆盖的不只是 `Controls`：`KeyboardAccelerator` 在
        /// `Microsoft.UI.Xaml.Input`、`Run` 在 `Documents`、`VisualState` 在 `VisualStateManager`…
        /// 所以候选表不能写死几个命名空间 —— 从元数据里把**所有** `Microsoft.UI.Xaml*` 下的
        /// 类型按短名索引起来，再按一个稳定的优先级排序。
        ///
        /// 🔴 这一条是变异臂打出来的：第一版只搜 Controls/根/Documents/Media/Shapes，
        /// 于是**正确的** `<KeyboardAccelerator Key="Enter"/>` 也会被判红 ——
        /// 一个会把正确写法判红的判据，最后一定会被人关掉。
        /// </summary>
        public IReadOnlyList<string> XamlTypeCandidates(string tag)
        {
            _xamlTagIndex ??= BuildXamlTagIndex();
            return _xamlTagIndex.TryGetValue(tag, out var list) ? list : Array.Empty<string>();
        }

        private Dictionary<string, List<string>> BuildXamlTagIndex()
        {
            var index = new Dictionary<string, List<string>>(StringComparer.Ordinal);

            foreach (var (reader, _) in _readers)
            {
                foreach (var handle in reader.TypeDefinitions)
                {
                    var definition = reader.GetTypeDefinition(handle);
                    var ns = reader.GetString(definition.Namespace);

                    if (!(ns == "Microsoft.UI.Xaml" || ns.StartsWith("Microsoft.UI.Xaml.", StringComparison.Ordinal)))
                    {
                        continue;
                    }

                    var name = reader.GetString(definition.Name);
                    var fullName = ns + "." + name;

                    if (!index.TryGetValue(name, out var list))
                    {
                        list = new List<string>();
                        index[name] = list;
                    }

                    if (!list.Contains(fullName))
                    {
                        list.Add(fullName);
                    }
                }
            }

            foreach (var list in index.Values)
            {
                list.Sort(CompareXamlNamespace);
            }

            return index;
        }

        private static int CompareXamlNamespace(string left, string right)
        {
            int Rank(string fullName)
            {
                var ns = fullName[..fullName.LastIndexOf('.')];
                return ns switch
                {
                    "Microsoft.UI.Xaml.Controls" => 0,
                    "Microsoft.UI.Xaml" => 1,
                    "Microsoft.UI.Xaml.Documents" => 2,
                    "Microsoft.UI.Xaml.Media" => 3,
                    "Microsoft.UI.Xaml.Shapes" => 4,
                    _ => 10,
                };
            }

            var byRank = Rank(left).CompareTo(Rank(right));
            return byRank != 0 ? byRank : string.CompareOrdinal(left, right);
        }

        public MetaType? Find(string fullName)
        {
            if (fullName.Length == 0)
            {
                return null;
            }

            if (_cache.TryGetValue(fullName, out var cached))
            {
                return cached;
            }

            var located = Locate(fullName);
            var type = located.Reader is null
                ? null
                : new MetaType(this, located.Reader, located.Handle!.Value, fullName);

            _cache[fullName] = type;
            return type;
        }

        public bool IsEnum(string typeName) => BaseTypeOf(typeName) == "System.Enum";

        public HashSet<string> EnumLiteralNames(string typeName)
        {
            var names = new HashSet<string>(StringComparer.Ordinal);
            var located = Locate(typeName);

            if (located.Reader is null)
            {
                return names; // 空集 ⇒ 任何成员都判红（宁可红，不要假绿）
            }

            foreach (var fieldHandle in located.Reader.GetTypeDefinition(located.Handle!.Value).GetFields())
            {
                var field = located.Reader.GetFieldDefinition(fieldHandle);
                if ((field.Attributes & FieldAttributes.Literal) != 0)
                {
                    names.Add(located.Reader.GetString(field.Name));
                }
            }

            return names;
        }

        public string BaseTypeName(MetadataReader reader, TypeDefinitionHandle handle)
        {
            var baseType = reader.GetTypeDefinition(handle).BaseType;
            return baseType.IsNil ? string.Empty : FullNameOf(reader, baseType);
        }

        private string BaseTypeOf(string typeName)
        {
            var located = Locate(typeName);

            if (located.Reader is null)
            {
                return string.Empty;
            }

            try
            {
                return BaseTypeName(located.Reader, located.Handle!.Value);
            }
            catch (Exception ex)
            {
                // 读不动就回空串（= "不知道"），不猜、也不静默当"不是枚举"：
                // 上层会因为拿不到判据而把它记进"未做值检查"的账。
                _warned.Add(typeName);
                if (_warned.Count <= 3)
                {
                    Console.Error.WriteLine($"⚠️ 元数据解析失败（已记账，不当作通过）：{typeName} — {ex.GetType().Name}");
                }

                return string.Empty;
            }
        }

        public (MetadataReader? Reader, TypeDefinitionHandle? Handle) Locate(string fullName)
        {
            var shortName = fullName.Contains('.') ? fullName[(fullName.LastIndexOf('.') + 1)..] : fullName;

            foreach (var (reader, _) in _readers)
            {
                foreach (var handle in reader.TypeDefinitions)
                {
                    var definition = reader.GetTypeDefinition(handle);
                    if (!string.Equals(reader.GetString(definition.Name), shortName, StringComparison.Ordinal))
                    {
                        continue;
                    }

                    var ns = reader.GetString(definition.Namespace);
                    var candidate = ns.Length == 0 ? shortName : ns + "." + shortName;

                    if (string.Equals(candidate, fullName, StringComparison.Ordinal))
                    {
                        return (reader, handle);
                    }
                }
            }

            return (null, null);
        }

        public string FullNameOf(MetadataReader reader, EntityHandle handle)
        {
            switch (handle.Kind)
            {
                case HandleKind.TypeDefinition:
                {
                    var definition = reader.GetTypeDefinition((TypeDefinitionHandle)handle);
                    var ns = reader.GetString(definition.Namespace);
                    var name = reader.GetString(definition.Name);
                    return ns.Length == 0 ? name : ns + "." + name;
                }

                case HandleKind.TypeReference:
                {
                    var reference = reader.GetTypeReference((TypeReferenceHandle)handle);
                    var ns = reader.GetString(reference.Namespace);
                    var name = reader.GetString(reference.Name);
                    return ns.Length == 0 ? name : ns + "." + name;
                }

                default:
                    return string.Empty;
            }
        }

        public void Dispose()
        {
            foreach (var pe in _peReaders)
            {
                pe.Dispose();
            }
        }
    }

