// XAML 探针：把「WinUI 那一半只能等一台 Windows」压到只剩 XamlCompiler 自己。
//
// 两个子命令：
//   emit-stubs  从真实 .xaml 里机械地生成 XAML 编译器本该生成的东西（x:Name 字段 +
//               InitializeComponent），供 compile/WinUiCompileProbe.csproj 把**仓库里的
//               真实 C#** 编一遍。（以前这份替身是手写的：11 个字段，多一个少一个没人知道。）
//   validate    拿 WinUI 自己的元数据逐条核对 XAML 里写的名字：元素类型、属性、事件、
//               附加属性、枚举成员、x:Bind 路径、资源键、code-behind 里的处理器。
//
// 🔴 为什么这件事值得做：2026-10-25 那三个"在 Windows 上会当场编译失败"的 bug 里，
//    有两个（`KeyboardAccelerator` 缺 import、`Key=","` 表达不出来）正是这一层能判红的。
//    第三个（`Windows.Graphics.SizeInt32` 被 `using Heyta.Windows.Host;` 抢走命名空间）
//    由 compile 那一半的**真实编译**抓。
//
// 🔴 为什么用 `System.Reflection.Metadata` 而不是 `MetadataLoadContext`：
//    后者要一个 NuGet 包，而本仓库的规矩是"引入第三方组件先过可维护性 + 许可证两道门"。
//    读 DLL 这件事 .NET 自带的解析器就够，多加一个包只是多一条会漂的依赖。
//
// ⚠️ 它**不是** XAML 编译器：样式键解析的优先级、模板合法性、`x:Bind` 的类型转换，
//    仍只有 Windows 上的 XamlCompiler 能 100% 回答。别把这里的 OK 读成"XAML 没问题"。

using System.Collections.Immutable;
using System.Reflection;
using System.Reflection.Metadata;
using System.Reflection.PortableExecutable;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml;
using System.Xml.Linq;

namespace Heyta.XamlProbe;

internal static class Program
{
    private const string PresentationNs = "http://schemas.microsoft.com/winfx/2006/xaml/presentation";
    private const string XamlDirectNs = "http://schemas.microsoft.com/winfx/2006/xaml";
    private const string UsingPrefix = "using:";

    /// <summary>
    /// 默认 xmlns 里的标签可能在哪个 CLR 命名空间下。顺序是**元数据里的真实分布**，
    /// 不是随手写的：`Grid`/`WebView2` 在 Controls，`Window`/`Application`/`RowDefinition`
    /// 在根命名空间（`RowDefinition`/`ColumnDefinition` 也在 Controls），`Run` 在 Documents。
    /// 判据是"元数据里找得到"，找不到就红 —— 这份候选表本身就是 2026-10-25 那次
    /// `Windows.Graphics.SizeInt32` 被抢走命名空间的同类问题的现场记录。
    /// </summary>
    private static readonly string[] ControlNsCandidates =
    {
        "Microsoft.UI.Xaml.Controls",
        "Microsoft.UI.Xaml",
        "Microsoft.UI.Xaml.Documents",
        "Microsoft.UI.Xaml.Media",
        "Microsoft.UI.Xaml.Shapes",
    };

    /// <summary>
    /// WinUI 内建资源键（不在我们的 tokens 生成物里，但确实存在于通用资源字典）。
    /// 白名单之外一律判红 —— 新键要人来看一眼它到底是内建，还是我们**应该**生成的。
    /// </summary>
    private static readonly HashSet<string> BuiltinResourceKeys = new(StringComparer.Ordinal)
    {
        "AccentButtonStyle",
    };

    private static int Main(string[] argv)
    {
        if (argv.Length == 0)
        {
            return Usage();
        }

        var command = argv[0];
        var opts = ParseOptions(argv.Skip(1));

        try
        {
            return command switch
            {
                "emit-stubs" => EmitStubs(opts),
                "validate" => Validate(opts),
                _ => Usage(),
            };
        }
        catch (Exception ex)
        {
            Console.Error.WriteLine($"❌ 探针自身异常（这不是被验代码的问题，是探针坏了）：{ex.Message}");
            Console.Error.WriteLine(ex.StackTrace);
            return 2;
        }
    }

    private static int Usage()
    {
        Console.Error.WriteLine("用法：");
        Console.Error.WriteLine("  Heyta.XamlProbe emit-stubs --xaml-dir <dir> --compile-dir <dir> --out <file>");
        Console.Error.WriteLine("  Heyta.XamlProbe validate   --xaml-dir <dir> --compile-dir <dir> --tokens <file> [--verbose]");
        return 64;
    }

    // ── emit-stubs ────────────────────────────────────────────────────────────

    private static int EmitStubs(Dictionary<string, string> opts)
    {
        var xamlDir = Require(opts, "xaml-dir");
        var outFile = Require(opts, "out");
        using var meta = MetadataIndex.FromCompileDir(Require(opts, "compile-dir"));

        var docs = LoadDocs(xamlDir);
        if (docs.Count == 0)
        {
            Console.Error.WriteLine($"❌ {xamlDir} 下没有 .xaml —— 探针没有输入，不能假装通过");
            return 1;
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// 由 apps/desktop-windows/xaml-probe/tool（emit-stubs）从 .xaml 机械生成，**不要手改**。");
        sb.AppendLine("// 它替身掉的东西只有两样：XAML 编译器本该生成的 x:Name 字段、以及 InitializeComponent()。");
        sb.AppendLine("// 其它每一行都是仓库里的真实代码（见 compile/WinUiCompileProbe.csproj 的 Compile Include）。");
        sb.AppendLine("#nullable disable");
        sb.AppendLine();

        var failures = 0;
        foreach (var doc in docs)
        {
            var decl = ReadClassDeclaration(doc);
            if (decl is null)
            {
                Console.Error.WriteLine($"❌ {doc.Relative}: 找不到 `partial class {doc.ClassName}` 的声明");
                failures++;
                continue;
            }

            if (!decl.Value.IsPartial)
            {
                Console.Error.WriteLine($"❌ {doc.Relative}: code-behind 的类没写 partial ⇒ XAML 编译器会直接拒绝");
                failures++;
                continue;
            }

            // 用**块作用域** namespace：同一个 .cs 里有三份 UI（App / MainWindow / SettingsWindow），
            // 而 file-scoped namespace 一份文件只能有一个（CS8954）。
            sb.AppendLine($"namespace {doc.ClassNamespace}");
            sb.AppendLine("{");
            sb.AppendLine($"{decl.Value.Modifiers}class {doc.ClassName}");
            sb.AppendLine("{");

            var codeBehind = File.ReadAllText(doc.CodeBehindPath);

            foreach (var (name, element) in NamedElements(doc))
            {
                var type = ElementClrType(element, meta);
                if (type is null)
                {
                    Console.Error.WriteLine(
                        $"❌ {doc.Relative}: x:Name=\"{name}\" 的标签 <{element.Name.LocalName}> 在元数据里找不到 CLR 类型");
                    failures++;
                    continue;
                }

                if (Regex.IsMatch(codeBehind, $@"\b(?:private|internal|public|protected)\s+[\w\.<>]+\s+{Regex.Escape(name)}\s*[;=]"))
                {
                    Console.Error.WriteLine(
                        $"❌ {doc.Relative}: x:Name=\"{name}\" 与 code-behind 里的手写字段重名（CS0102 / CS0111）");
                    failures++;
                    continue;
                }

                var init = type.IsValueType ? "default" : "new()";
                sb.AppendLine($"    private {type.FullName} {name} = {init};");
            }

            if (decl.Value.HasInitializeComponent)
            {
                Console.Error.WriteLine(
                    $"❌ {doc.Relative}: code-behind 自己写了 InitializeComponent() ⇒ 与生成物重复（XAML 编译器会报 CS0111）");
                failures++;
            }
            else
            {
                sb.AppendLine();
                sb.AppendLine("    private void InitializeComponent() { }");
            }

            sb.AppendLine("}");
            sb.AppendLine("}");
            sb.AppendLine();
        }

        if (failures > 0)
        {
            Console.Error.WriteLine($"❌ 替身生成失败：{failures} 处");
            return 1;
        }

        var dir = Path.GetDirectoryName(outFile);
        if (!string.IsNullOrEmpty(dir))
        {
            Directory.CreateDirectory(dir);
        }

        File.WriteAllText(outFile, sb.ToString());
        Console.WriteLine($"✅ 生成 XAML 替身：{Path.GetFileName(outFile)}（{docs.Count} 个 .xaml）");
        return 0;
    }

    // ── validate ──────────────────────────────────────────────────────────────

    private static int Validate(Dictionary<string, string> opts)
    {
        var xamlDir = Require(opts, "xaml-dir");
        var compileDir = Require(opts, "compile-dir");
        var tokens = Require(opts, "tokens");
        var verbose = opts.ContainsKey("verbose");

        using var meta = MetadataIndex.FromCompileDir(compileDir);
        var docs = LoadDocs(xamlDir);
        var resourceKeys = LoadResourceKeys(tokens);

        var problems = new List<string>();
        var checkedItems = 0;
        var uncheckedValues = new List<string>();

        void Ok(string what)
        {
            checkedItems++;
            if (verbose)
            {
                Console.WriteLine($"OK  {what}");
            }
        }

        void Fail(string where, string what)
        {
            problems.Add($"{where}: {what}");
            Console.Error.WriteLine($"❌ {where}: {what}");
        }

        foreach (var doc in docs)
        {
            if (!File.Exists(doc.CodeBehindPath))
            {
                Fail(doc.Relative, $"XAML 有 x:Class 但 code-behind 不存在：{Path.GetFileName(doc.CodeBehindPath)}");
                continue;
            }

            var codeBehind = File.ReadAllText(doc.CodeBehindPath);
            var decl = ReadClassDeclaration(doc);
            var rootTag = doc.Root.Name.LocalName;
            var rootType = ElementClrType(doc.Root, meta);

            if (decl is null)
            {
                Fail(doc.Relative, $"code-behind 里找不到 `partial class {doc.ClassName}`");
            }
            else
            {
                if (!decl.Value.IsPartial)
                {
                    Fail(doc.Relative, "code-behind 的类没写 partial");
                }
                else
                {
                    Ok($"{doc.Relative}: partial class {doc.ClassName}");
                }

                var declaredBase = decl.Value.BaseType;
                if (declaredBase is { Length: > 0 } && declaredBase != rootTag)
                {
                    Fail(doc.Relative, $"code-behind 基类是 {declaredBase}，而 XAML 根元素是 <{rootTag}>（XAML 编译器会拒）");
                }
                else if (declaredBase is { Length: > 0 })
                {
                    Ok($"{doc.Relative}: 基类 {declaredBase} 与根元素一致");
                }
            }

            if (rootType is null)
            {
                Fail(doc.Relative, $"根元素 <{rootTag}> 在元数据里找不到");
            }
            else
            {
                Ok($"{doc.Relative}: 根元素 {rootType.FullName}");
            }

            var seenNames = new HashSet<string>(StringComparer.Ordinal);

            foreach (var element in doc.Root.DescendantsAndSelf())
            {
                var where = $"{doc.Relative}:{LineOf(element)} <{element.Name.LocalName}>";
                var local = element.Name.LocalName;
                var dot = local.IndexOf('.');
                var elementType = dot > 0 ? null : ElementClrType(element, meta);

                // `Application.Resources` / `Grid.RowDefinitions` 这类**属性元素**：
                // 标签里的点不是命名空间，是"某个类型的某个属性"。
                if (dot > 0)
                {
                    var owner = local[..dot];
                    var prop = local[(dot + 1)..];
                    var ownerType = ResolveByTag(owner, element, meta);
                    var property = ownerType?.FindProperty(prop);

                    if (ownerType is null)
                    {
                        Fail(where, $"属性元素的宿主类型 <{owner}> 在元数据里找不到");
                    }
                    else if (property is null)
                    {
                        Fail(where, $"{ownerType.FullName} 上没有属性 {prop}（属性元素写错了）");
                    }
                    else
                    {
                        Ok($"{where} → {ownerType.Name}.{prop}");
                        elementType = meta.Find(property.TypeName);
                        if (elementType is null)
                        {
                            Fail(where, $"{ownerType.Name}.{prop} 的类型解析不了：{property.TypeName}");
                        }
                    }
                }
                else if (elementType is null)
                {
                    Fail(where, "标签在元数据里找不到对应的 CLR 类型（命名空间猜错 / 类型名拼错）");
                }
                else
                {
                    Ok($"{where} → {elementType.FullName}");
                }

                var dataType = DataTypeInScope(element, meta);

                foreach (var attribute in element.Attributes())
                {
                    if (attribute.IsNamespaceDeclaration)
                    {
                        continue;
                    }

                    var aNs = attribute.Name.NamespaceName;

                    if (aNs == XamlDirectNs)
                    {
                        ValidateXamlDirective(doc, element, attribute, dataType, meta, codeBehind, Fail, Ok);
                        continue;
                    }

                    if (aNs.Length > 0)
                    {
                        // mc:Ignorable / d: 设计时属性 —— 不是运行时的东西
                        if (aNs.StartsWith("http://schemas.openxmlformats.org/markup-compatibility", StringComparison.Ordinal)
                            || aNs.StartsWith("http://schemas.microsoft.com/expression/blend", StringComparison.Ordinal))
                        {
                            continue;
                        }

                        Fail(where, $"不认识的属性命名空间：{aNs}（{attribute.Name}）");
                        continue;
                    }

                    if (elementType is null)
                    {
                        continue; // 元素已经不认识了，别再报第二遍
                    }

                    var aName = attribute.Name.LocalName;

                    if (aName == "Name")
                    {
                        Ok($"{where} Name=\"{attribute.Value}\"");
                        continue;
                    }

                    if (aName.Contains('.'))
                    {
                        ValidateAttachedProperty(where, aName, attribute.Value, meta, Fail, Ok, uncheckedValues);
                        continue;
                    }

                    ValidateMember(where, elementType, aName, attribute.Value, meta, resourceKeys, codeBehind, dataType, Fail, Ok, uncheckedValues);
                }

                foreach (var nameAttribute in element.Attributes()
                             .Where(a => a.Name.NamespaceName == XamlDirectNs && a.Name.LocalName == "Name"))
                {
                    if (!seenNames.Add(nameAttribute.Value))
                    {
                        Fail(where, $"x:Name=\"{nameAttribute.Value}\" 在同一份 XAML 里重复（XAML 编译器会拒）");
                    }
                }
            }
        }

        Console.WriteLine();
        Console.WriteLine($"核对项 {checkedItems} ｜ 未做值检查的 {uncheckedValues.Count} 处 ｜ 问题 {problems.Count} 处");
        foreach (var group in uncheckedValues.GroupBy(v => v).OrderByDescending(g => g.Count()))
        {
            Console.WriteLine($"   · 值不检查（由 TypeConverter 解释，本层判不了）：{group.Key} × {group.Count()}");
        }

        if (problems.Count > 0)
        {
            Console.Error.WriteLine($"RESULT=FAIL（{problems.Count} 处）");
            return 1;
        }

        Console.WriteLine("RESULT=OK");
        return 0;
    }

    private static void ValidateXamlDirective(
        XamlDoc doc,
        XElement element,
        XAttribute attribute,
        MetaType? dataType,
        MetadataIndex meta,
        string codeBehind,
        Action<string, string> fail,
        Action<string> ok)
    {
        var where = $"{doc.Relative}:{LineOf(element)} <{element.Name.LocalName}>";

        switch (attribute.Name.LocalName)
        {
            case "Name":
            case "Uid":
            case "Class":
            case "Key":
            case "FieldModifier":
                ok($"{where} x:{attribute.Name.LocalName}");
                return;

            case "DataType":
            {
                var type = ResolveXamlTypeName(attribute.Value, element, meta);
                if (type is null)
                {
                    fail(where, $"x:DataType=\"{attribute.Value}\" 解析不到类型");
                }
                else
                {
                    ok($"{where} x:DataType → {type.FullName}");
                }

                return;
            }

            case "Bind":
                ValidateBindPath(where, attribute.Value, dataType, meta, fail, ok);
                return;

            default:
                ok($"{where} x:{attribute.Name.LocalName}（本层不判）");
                return;
        }
    }

    private static void ValidateBindPath(
        string where,
        string value,
        MetaType? dataType,
        MetadataIndex meta,
        Action<string, string> fail,
        Action<string> ok)
    {
        var path = ExtractBindPath(value);
        if (path is null)
        {
            ok($"{where} x:Bind（无路径，绑到 code-behind 本身，本层不判）");
            return;
        }

        if (dataType is null)
        {
            ok($"{where} x:Bind {path}（无 x:DataType ⇒ 绑到 code-behind，本层不判）");
            return;
        }

        var root = Regex.Match(path, @"^[A-Za-z_]\w*").Value;
        if (root.Length == 0)
        {
            fail(where, $"x:Bind 路径读不出根标识符：{value}");
            return;
        }

        if (dataType.FindProperty(root) is null)
        {
            fail(where, $"x:Bind {path}：{dataType.FullName} 上没有成员 {root}（编译期绑定会 CS1061）");
        }
        else
        {
            ok($"{where} x:Bind {path} → {dataType.Name}.{root}");
        }
    }

    private static void ValidateMember(
        string where,
        MetaType elementType,
        string name,
        string value,
        MetadataIndex meta,
        HashSet<string> resourceKeys,
        string codeBehind,
        MetaType? dataType,
        Action<string, string> fail,
        Action<string> ok,
        List<string> uncheckedValues)
    {
        var property = elementType.FindProperty(name);
        var isEvent = property is null && elementType.HasEvent(name);

        if (property is null && !isEvent)
        {
            fail(where, $"{elementType.FullName} 上没有属性/事件 {name}");
            return;
        }

        if (isEvent)
        {
            if (!Regex.IsMatch(codeBehind, $@"\b(?:async\s+)?(?:void|Task|ValueTask)\s+{Regex.Escape(value)}\s*\("))
            {
                fail(where, $"事件 {name}=\"{value}\"：code-behind 里没有同名方法（XAML 编译器会报未找到）");
            }
            else
            {
                ok($"{where} 事件 {name}=\"{value}\"");
            }

            return;
        }

        if (value.StartsWith('{'))
        {
            var extension = Regex.Match(value, @"^\{\s*([A-Za-z:]+)");
            var kind = extension.Success ? extension.Groups[1].Value : "?";

            if (kind is "ThemeResource" or "StaticResource")
            {
                var key = Regex.Match(value, @"\{\s*(?:Theme|Static)Resource\s+([^\s\}]+)").Groups[1].Value;
                if (key.Length == 0)
                {
                    fail(where, $"{name} 的资源引用读不出键名：{value}");
                }
                else if (resourceKeys.Contains(key) || BuiltinResourceKeys.Contains(key))
                {
                    ok($"{where} {name} → {kind} {key}");
                }
                else
                {
                    fail(where, $"{name} 引用的资源键 \"{key}\" 既不在 tokens 生成物里，也不在内建白名单里");
                }

                return;
            }

            if (kind is "x:Bind" or "x:Bind")
            {
                ValidateBindPath(where, value, dataType, meta, fail, ok);
                return;
            }

            if (kind is "Binding" or "TemplateBinding" or "CompiledBinding")
            {
                ok($"{where} {name} → {kind}（运行时绑定，本层不判路径）");
                return;
            }

            fail(where, $"{name} 用了本层不认识的标记扩展 {{{kind} …}} —— 新写法的校验要人补一条");
            return;
        }

        var typeName = property!.TypeName;

        if (meta.IsEnum(typeName))
        {
            var literals = meta.EnumLiteralNames(typeName);
            var parts = value.Split(new[] { ',', '|' }, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

            // 🔴 空集**不能**算通过：`,|` 这类值按分隔符切开之后一个成员名都不剩，
            //    循环体一次都不跑，于是"全部合法"—— 这正是 2026-10-25 那个
            //    `Key=","` bug 的形状：它写不出来，而一个"切完再比"的判据会把它放行。
            if (parts.Length == 0 || value.Trim().Length == 0)
            {
                fail(where, $"{name}=\"{value}\" 里读不出任何 {typeName} 的成员名");
                return;
            }

            foreach (var part in parts)
            {
                if (!literals.Contains(part))
                {
                    fail(
                        where,
                        $"{name}=\"{part}\" 不是 {typeName} 的成员（可用：{string.Join(" / ", literals.OrderBy(x => x).Take(12))}…）");
                    return;
                }
            }

            ok($"{where} {name}={value} ∈ {typeName}");
            return;
        }

        if (typeName == "System.Boolean")
        {
            if (!bool.TryParse(value, out _))
            {
                fail(where, $"{name}=\"{value}\" 不是布尔值");
            }
            else
            {
                ok($"{where} {name}={value} (bool)");
            }

            return;
        }

        if (typeName is "System.Double" or "System.Single" or "System.Int32" or "System.Int64" or "System.UInt32")
        {
            if (!double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out _))
            {
                fail(where, $"{name}=\"{value}\" 不是数字");
            }
            else
            {
                ok($"{where} {name}={value} (数值)");
            }

            return;
        }

        // 有 TypeConverter 的结构体（GridLength / FontWeight / Thickness / Uri…）：
        // 值是转换器的事，本层不猜。**显式记账**，不装作验过。
        uncheckedValues.Add($"{name}:{typeName}");
        ok($"{where} {name}（值由 TypeConverter 解释）");
    }

    private static void ValidateAttachedProperty(
        string where,
        string dottedName,
        string value,
        MetadataIndex meta,
        Action<string, string> fail,
        Action<string> ok,
        List<string> uncheckedValues)
    {
        var dot = dottedName.IndexOf('.');
        var ownerName = dottedName[..dot];
        var propName = dottedName[(dot + 1)..];

        var ownerType = meta.Find("Microsoft.UI.Xaml.Controls." + ownerName)
                        ?? meta.Find("Microsoft.UI.Xaml." + ownerName);

        if (ownerType is null)
        {
            fail(where, $"附加属性 {dottedName}：宿主类型 {ownerName} 在元数据里找不到");
            return;
        }

        var setter = ownerType.FindStaticMethod("Set" + propName, parameterCount: 2);
        if (setter is null)
        {
            fail(where, $"附加属性 {dottedName}：{ownerType.FullName} 上没有静态 Set{propName}(…)");
            return;
        }

        var valueType = setter.ParameterTypes[1];

        if (meta.IsEnum(valueType))
        {
            if (!meta.EnumLiteralNames(valueType).Contains(value))
            {
                fail(where, $"附加属性 {dottedName}=\"{value}\" 不是 {valueType} 的成员");
                return;
            }
        }
        else if (valueType is "System.Double" or "System.Int32")
        {
            if (!double.TryParse(value, System.Globalization.NumberStyles.Float, System.Globalization.CultureInfo.InvariantCulture, out _))
            {
                fail(where, $"附加属性 {dottedName}=\"{value}\" 不是数字");
                return;
            }
        }
        else
        {
            uncheckedValues.Add($"{dottedName}:{valueType}");
        }

        ok($"{where} 附加属性 {dottedName}={value}");
    }

