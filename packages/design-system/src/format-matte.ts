/**
 * JPEG 铺底色的**格式常量**（不是设计色）
 * ======================================
 *
 * 为什么这一枚值必须住在 L0 并且**写成字面量**：
 *
 * JPEG 编码没有 alpha 通道。把一张带透明边缘的 PNG（截图几乎都有）画进 canvas
 * 再导出 JPEG 时，透明像素会被铺成**黑**底 —— 深色的界面字压在黑底上等于没了。
 * 所以编码前必须先 `fillRect` 一层不透明底色。
 *
 * 🔴 三条都不能变：
 *
 *   1. **`canvas.getContext('2d').fillStyle` 不接受 `var()`。** 它不是 CSS 声明，
 *      是 JS 给绘图上下文的字符串 —— 传 `'var(--ht-color-background)'` 会被静默忽略、
 *      保持默认黑色，于是症状正好是这段代码要防的那个（**没有报错**，图变黑）。
 *      这与 `ICON_SIZE` 必须是数字是同一个原因（SVG 属性不解析 `var()`，见 `icon-size.ts`）。
 *   2. **它不是主题色。** 主题色在暗色下是近黑（`slate-950`），拿它当 JPEG 底色
 *      就把黑底问题原样搬回来。铺白说的是"这是一张要贴在白纸/白底聊天窗里的图"，
 *      与当前皮肤无关。
 *   3. **它不能写在 L4 视图里。** `check:l4` / `check:design` 禁的是 L4 出现裸色值 ——
 *      那条规则的意图是"视图层不定义取值"。取值属于 L0，引用属于 L4，所以常量住这里、
 *      消费点 import 它。这比往两张允许表里各加一条 `why` 更诚实：
 *      允许表是给"真的没有别的路"的那一类留的，这里明明有路。
 */

