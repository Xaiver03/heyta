#!/usr/bin/env node
/**
 * 把「法律文本自己的名字与摘要」搬进两张词条表
 * =============================================
 *
 * 用法：
 *
 *     node scripts/gen-site-copy.mjs            # 写进 packages/i18n 的两张表
 *     node scripts/gen-site-copy.mjs --check    # 只校验，不一致就退出 1
 *
 * 🔴 **为什么这 72 条是生成的，而同一批页面的页脚标签是手写的。**
 *
 * `packages/i18n` 的纪律是「**界面文案**的唯一事实源」。一条法律文档的
 * 页脚标签（「隐私政策」）是界面文案 —— 它短、要挑字、要服从站点 IA，
 * 所以手写在那两张表里（见 `site.footer.legal.*`）。
 *
 * 但一条文档的**标题与摘要**不是界面文案，它是**对外承诺本身**：
 * 它与正文同源、同版本、同一次法务复核签发。写第二份就是给自己造漂移：
 * 改了 `privacy.ts` 的标题而页脚/h1/`<title>` 还印着旧的，
 * 而这三处恰好是用户点进去之前读到的一切。
 *
 * 所以这里走的是本仓库已经用过的另一条路子 —— **生成物 + 门禁**
 * （`server/src/copy.generated.ts` 用 `check:server-copy` 钉住，同一个形状）：
 * 事实源只有 `src/index.ts` 那九份，站点侧要的是它的**投影**。
 *
 * ⚠️ 前置：`pnpm --filter @heyta/legal build`。这个脚本读的是 `dist/`
 *（不是 `src/` —— 本包的模块图用了 `./x.js` 这种 Node 的 ESM 解析器
 * 不会映射回 `.ts` 的写法，直接 import 源码会 `ERR_MODULE_NOT_FOUND`）。
 * 顺序天然满足：`pnpm check` 里 `pnpm build` 在任何门禁之前。
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { LEGAL_DOCUMENTS } from '../dist/index.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const I18N = resolve(HERE, '../../i18n/src/locales');

const CHECK = process.argv.includes('--check');

const START = '<<<generated:packages/legal/scripts/gen-site-copy.mjs>>>';
const END = '<<<end:generated:packages/legal/scripts/gen-site-copy.mjs>>>';

/** 与落地页 `RichText` 同一套标记，纯文本出口前必须摘掉（`og:`/`<meta>` 不解析标记）。 */
function stripMarkup(text) {
  return text.replaceAll(/\*\*(.+?)\*\*/g, '$1').replaceAll(/`([^`]+)`/g, '$1');
}

/** 站点侧的 `<title>` 后缀。两版各用自己那一种破折号，与既有 `site.*.seo.title` 一致。 */
const BRAND = { 'zh-CN': ' —— heyta', en: ' — heyta' };

/**
 * 一份文档 → 四条站点文案。**页脚标签不在这里** —— 那是界面文案，手写。
 *
 * ⚠️ `lede` 与 `seo.description` 是两条而不是同一条的引用：前者进页面
 * （`RichText` 会把 `**` 渲染成粗体），后者进 `<meta name="description">`
 * 与分享卡片（没有渲染器，标记会按字面出现）。
 */
function entriesFor(document, locale) {
  const title = document.title[locale];
  const summary = document.summary[locale];
  return [
    [`site.legal.${document.id}.title`, title],
    [`site.legal.${document.id}.lede`, summary],
    [`site.legal.${document.id}.seo.title`, `${title}${BRAND[locale]}`],
    [`site.legal.${document.id}.seo.description`, stripMarkup(summary)],
  ];
}

function block(locale) {
  // 🔴 这两行注释**必须是纯 ASCII**：英文表里不许出现汉字（`check:ui-language`
  // 的判据之一，理由写在 en.ts 的文件头 —— "把中文复制过来当英文交差"）。
  // 注释也是那张表的一部分，写中文就是给它第一次红。
  return [
    `  // ${START}`,
    `  // Generated by packages/legal/scripts/gen-site-copy.mjs - do not edit by hand.`,
    `  // Source of truth: the titles and summaries in src/documents/*.ts.`,
    ...LEGAL_DOCUMENTS.flatMap((document) =>
      entriesFor(document, locale).map(
        ([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`,
      ),
    ),
    `  // ${END}`,
  ].join('\n');
}

const START_LINE = `  // ${START}`;
const END_LINE = `  // ${END}`;

const targets = [
  { file: resolve(I18N, 'zh-CN.ts'), locale: 'zh-CN' },
  { file: resolve(I18N, 'en.ts'), locale: 'en' },
];

let drift = 0;

for (const { file, locale } of targets) {
  const source = readFileSync(file, 'utf8');
  const from = source.indexOf(START_LINE);
  const endAt = source.indexOf(END_LINE);
  const existing = from !== -1 && endAt !== -1 ? source.slice(from, endAt + END_LINE.length) : null;
  const generated = block(locale);

  if (existing === generated) continue;

  if (CHECK) {
    process.stderr.write(
      `🔴 ${file} 里的法律文本站点文案与 @heyta/legal 不一致。\n` +
        (existing === null
          ? '   （这一段还没有被生成过 —— 跑一次生成器。）\n'
          : '   跑 `node packages/legal/scripts/gen-site-copy.mjs` 再提交。\n'),
    );
    drift += 1;
    continue;
  }

  if (existing !== null) {
    writeFileSync(file, source.replace(existing, generated), 'utf8');
  } else {
    // 插进对象字面量的末尾。两张表的收尾不一样（zh 是 `} as const;`，
    // en 是 `} satisfies Record<MessageKey, string>;`），**两个都试**：
    // 多余属性检查正是靠"写在对象里面"才成立，写到外面就是编译错误 ——
    // 那也就是这个锚点写错时的表现（响亮，不会静默生成一份少一段的表）。
    const anchors = ['\n} satisfies', '\n} as const'];
    const anchor = Math.max(...anchors.map((needle) => source.lastIndexOf(needle)));
    if (anchor === -1) {
      throw new Error(
        `${file} 里找不到对象字面量的结尾（} satisfies / } as const），生成器需要更新。`,
      );
    }
    writeFileSync(file, `${source.slice(0, anchor)}\n\n${generated}${source.slice(anchor)}`, 'utf8');
  }
  process.stdout.write(` 写入 ${file} (${LEGAL_DOCUMENTS.length * 4} 条)\n`);
}

if (CHECK && drift > 0) process.exit(1);
if (CHECK) process.stdout.write(`法律文本站点文案与 @heyta/legal 一致。\n`);
