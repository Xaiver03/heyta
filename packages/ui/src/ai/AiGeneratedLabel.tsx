/**
 * AI 生成合成内容的**显式标识**（共享层，四端同一份）
 * =====================================================
 *
 * 《人工智能生成合成内容标识办法》与 GB 45438-2025 要求生成合成的文本内容在界面的
 * 适当位置带上"这是 AI 生成的"提示。这个组件就是那句提示本身：它不是解释、不是
 * 免责声明、也不是"来源：本机/远程"那种端点标签（那是 `AiPanelHead` 的 `tag`，
 * 说的是数据去了哪里，不回答"这段话是谁写的"）。
 *
 * ## 为什么是**灰色小字**，而不是一枚色块（2026-10-21 改）
 *
 * 上一版是一条 `primary-subtle` 蓝底 + 内边距 + 圆角的胶囊，字号 11px。
 * 它在功能上没毛病（文字对、位置对、测试全绿），但那是**错误的视觉语义**：
 *
 *   1. **胶囊 = 可点的东西。** 同一个界面里，圆角+底色的胶囊是 `.ht-chip`
 *      这类筛选控件与标签的形状；一个不可点的法定提示长成那样，用户会去点它。
 *   2. **它抢正文的注意力。** 标识必须"可被用户明显感知"，但"明显"不等于
 *      "比被标识的内容更醒目"。蓝底在整块中性色界面上是**最高对比**的那一格，
 *      于是读者第一眼看到的是"AI 生成合成内容"，而不是回答本身。
 *   3. **11px 是"极致紧凑标签"档**（`tokens.css` 的原话），而法定标识是要被
 *      **读**的：中文 7 个字在 11px 下已经接近屏上最小可读边界。
 *
 * 同行怎么做（2026-10-21 逐个核对过产品形态）：ChatGPT 的
 * "ChatGPT can make mistakes…"、Claude 的 "Claude can make mistakes…"、
 * Copilot 的 "AI-generated content may be incorrect"、Gemini 的
 * "Gemini may display inaccurate info…"、Apple Intelligence 的
 * "Generated by Apple Intelligence" —— **全部是正文下方的灰字**，
 * 没有一家用彩色胶囊。法规只要求"可被明显感知"（《标识办法》对文本的要求是
 * "在文本的起始、末尾或者中间适当位置添加文字提示或者通用符号提示"），
 * 没有要求高对比底色，所以"灰字"与"合规"不冲突。
 *
 * ⇒ 现在的形状：`caption` 档（12px，辅助文字下限）+ `color.foreground-muted`（灰）
 *   + 4px 上距 + 贴左，**没有**底色/内边距/圆角。
 *   对比度由 `packages/design-system/tests/tokens.spec.ts` 里那对
 *   `--ht-color-foreground-muted` × 内容色（≥ 4.5:1）守着 —— 挑 `muted` 而不是
 *   `subtle` 就是因为后者在亮色下只有 4.76:1、且语义上更接近"不可用"。
 *
 * ## 🔴 位置：在被标识内容的**下方**（这是备案材料里写着的一句话）
 *
 * `docs/operations/cac-algorithm-filing/备案单一事实源.json` 的
 * `userSafeguards.visibleLabel` 与自评估正文写的是"展示在七类 AI 产出文本的**下方**"。
 * 2026-10-21 自核时发现**代码与材料对不上**：四个单步提案面板 + 助手的提案卡
 * 都把标识摆在内容**上方**。改的是代码（不是材料）：材料那句话是对的，
 * 而且"脚注在内容下方"本来就是同行的做法。判据落在各面板 spec 的 DOM 顺序断言里。
 *
 * ## 文案一律宿主注入
 *
 * 与 `AiPanel` 同一理由：本包不 import `@heyta/i18n`（i18n 自带一份 React，
 * 四端会同时中招）。宿主从 `common.ai.generatedLabel` 取词后传进来。
 *
 * 🔴 `label` **必填、没有默认值**：默认值会让"某个 AI 输出面接漏了"表现为
 * 一个仍然渲染着正确文字的位置，而那正是这件事最容易失效的方式。
 */

import React, { useMemo } from 'react';
import { Text, View } from 'react-native';

import { useHeytaText, useHeytaTokens } from '../theme.js';
import { aiGeneratedLabelStyle } from './generated-label-style.js';

export interface AiGeneratedLabelProps {
  /** 已翻好的标识文字（`common.ai.generatedLabel`）。 */
  readonly label: string;
  /** 各输出面自己的 testID；判据按它定位。 */
  readonly testID?: string;
}

export function AiGeneratedLabel({
  label,
  testID,
}: AiGeneratedLabelProps): React.JSX.Element {
  const tokens = useHeytaTokens();
  const text = useHeytaText();

  // 样式计划住在纯模块里（见 `generated-label-style.ts` 文件头）：
  // 组件只负责把它贴到屏幕上，不在渲染体里重新决定字号与颜色。
  const style = useMemo(() => aiGeneratedLabelStyle(tokens, text), [tokens, text]);

  return (
    <View style={style.frame} testID={testID ?? 'ai-generated-label'}>
      {/* 🔴 `style.label` 只带字号/字重，**不带颜色** —— 而 `<Text>` 没有颜色时会画成
          纯黑，暗色主题下等于看不见。语义文字样式自带默认前景色，再把 label 那层
          贴上去做微调（顺序不能反：反过来语义色就盖掉了）。 */}
      <Text style={[text['row-meta'], style.label]}>{label}</Text>
    </View>
  );
}
