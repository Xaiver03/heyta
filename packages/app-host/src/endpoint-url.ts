/**
 * 服务端地址拼接（**宿主无关**）
 * ==============================
 *
 * 服务端根地址是**用户手填**的，`http://127.0.0.1:3000` 与 `https://sync.example.com/`
 * 都会出现。拼接必须容忍末尾斜杠，否则会拼出 `//api/...`。
 *
 * 🔴 为什么是一个单独的文件、而不是每个调用点各写一份：
 * 权益探测（`entitlement.ts`）与认证（`hosted-auth.ts`）都要拼 URL。
 * 本仓库已经三次记过"同一件事两个实现必然漂移"（AGENTS.md §3.5），
 * 而这条拼接虽然只有一行，漂移的症状（一个双斜杠、一个漏斜杠）
 * 恰恰是**只在某一种填法下才出现**的那种 —— 手填地址的场景里最容易漏测。
 */

/**
 * 把根地址与端点路径拼成完整 URL。
 *
 * 只去掉**末尾**的斜杠：路径内部的斜杠是端点定义的一部分，不能动。
 * 根地址为空时返回相对路径 —— 调用方各自决定空地址该怎么处理
 * （认证与权益探测都在发请求之前就把空地址判成"未配置"）。
 */
export function joinEndpointUrl(baseUrl: string, path: string): string {
  return `${baseUrl.replace(/\/+$/, '')}${path}`;
}
