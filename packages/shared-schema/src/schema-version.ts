/**
 * 所有操作与状态快照的当前 schema 版本。
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  政策：**默认不 bump**。本文件从第一天起就把这条政策写死，避免重蹈覆辙。
 *
 *  这套政策直接继承自 Super Productivity（MIT）的实战教训。它记录的代价是真实的：
 *
 *  · bump 是**近乎单向的栅栏** —— 一旦任何 op 带上了新版本号，就**无法回退**。
 *    回退后的客户端会在自己已经写出的 v(N+1) op 上卡死，`USE_REMOTE` 恢复路径
 *    遇到它们会直接抛异常。
 *
 *  · **bump 保护不了已发布的客户端。** 旧客户端（上游是 v17.0.0–v18.14.0）会
 *    "容忍"若干版本，并且**未迁移就直接应用**，只弹一次警告 —— 这比直接拒绝更危险。
 *    更糟的是它会**推进服务端游标**，从而永久跳过那些被挡下的 op，即使用户之后升级了。
 *
 *  · 因此：**若旧客户端能未迁移地应用，就应该用 payload 标记（envelope 模式）
 *    向前兼容，而不是 bump 版本号。** 只有"必须把旧客户端硬栅栏在外面"的语义变更，
 *    才值得付出 bump 的代价。
 *
 *  · 上游记录的反例：v4 是为一个**纯标记变更**做的 bump —— 那次根本不需要 bump，
 *    却把所有滞后客户端栅栏住了。**不要重复这个错误。**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 若确实需要 bump：
 *   1. 先问"旧客户端能未迁移地应用吗？" 能 → 用 envelope，不要 bump
 *   2. 只有转换型迁移（字段改名/删除、op 被丢弃）或必须硬栅栏的语义才 bump
 *   3. bump 时**先**递增本常量，**再**添加迁移，两者必须在同一个 PR
 */

