/**
 * 邮箱+口令这条路的 **HTTP 契约**（服务端与四个宿主共用）
 * ======================================================
 *
 * 所以这里只放**必须跨端逐字相同**的东西：路径、服务端给的稳定机器码、口令长度界限。
 *
 * 它是**纯可加**的：`CURRENT_SCHEMA_VERSION` 只管 op / snapshot，不 bump。
 *
 * ## 🔴 为什么没有 zod 请求体（与计划 §3 的偏离，当场记在这里）
 *
 * 计划原本写"把 `server/src/api.ts` 里 auth 的 zod 搬进 shared-schema"。搬一半的契约
 * 比没有契约更危险：那五条 zod 只描述**服务端怎么校验输入**，四个宿主一个都不消费它们
 * （宿主发请求、不校验自己的请求）。把它们搬过来而服务端那边留着 `safeParse`，
 * 就是同一个校验规则的两份实现 —— §3.5 抽 `ids.ts` 那次"新版写好了、旧版从没删"
 * 正是这个形状。所以真正会漂移、而且漂移了会**静默**的三样东西才值得共享：
 *
 * 1. **路径**：服务端注册的字符串与客户端请求的字符串。不一致的症状是 404，
 *    而 404 在客户端归成"请求被拒"，用户看到的是一句"登录失败"。
 * 2. **`code` 词表**：服务端按它选状态码、客户端按它选词条与按钮。客户端是
 *    **白名单**消费（见 app-host 的 `FAILURE_REASON_BY_SERVER_CODE`），所以这里
 *    的词表就是"双方认得的同一批字符串"的唯一真源。
 * 3. **长度界限**：界面用它在输入时挡（`maxLength` 不适用，见下），服务端用它拒。
 *    两处不一致的表现是"界面让输、服务端 400"，用户完全不知道发生了什么。
 *
 * ⚠️ 第 3 条有个反直觉的细节：**界面上不许给口令框加 `maxlength`**。
 * HTML 的 `maxlength` 按 **UTF-16 单元**数，一个 emoji 占两个单元 —— 那会
 * **静默截断**用户真正要设的口令（NIST SP 800-63B 明令禁止 silent truncation：
 * 截断后的口令与用户心里那句不是同一个东西，而它会被存下来）。
 * 所以界限在这里只用于**提示文案与提交前的校验**，拒与存由服务端权威判定。
 */

/**
 * 服务端认证路由注册的**相对**路径（服务端挂在 `prefix: '/api'` 下，
 * 见 `server/src/server.ts`）。
 *
 * 🔴 存的是相对形状而不是 `/api/...`：那串前缀属于部署，服务端注册时就写着它，
 * 客户端拼接时再补一次。两边各持有一半，才是事实的分布方式。
 */
export const AUTH_PASSWORD_PATHS = {
  /** 建号并设口令（成功语义是"去看收件箱"，不发会话）。 */
  register: '/register/email-password',
  /** 换会话。 */
  login: '/login/email-password',
  /** 发一封重置口令的邮件。**响应与账号是否存在无关**。 */
  forgot: '/password/forgot',
  /** 用邮件链接里的一次性令牌换新口令。成功**不发会话**。 */
  reset: '/password/reset',
  /** 已登录改口令。当前设备换新会话、其余设备全部掉线。 */
  change: '/password/change',
  /**
   * 已登录**给账号加上第一个口令**（纯通行密钥 / 魔法链接注册的账号 `passwordHash` 为 null）。
   *
   * 🔴 它不是 `change` 的别名，两条路的后果不一样：
   *   · `change` 要验当前口令、bump `tokenVersion` ⇒ 其余设备全部掉线，当前设备换新会话；
   *   · `set` 没有当前口令可验、**不 bump** ⇒ 它是**加一个认证器**，不是换一把钥匙，
   *     把别的设备踢下线在这条路上没有任何安全收益（这个人本来就登录着）。
   *
   * 为什么不能靠 `forgot` 代劳：`requestPasswordReset` 对**没有口令认证器**的账号
   * 刻意不发信（反枚举），所以那条路对这类账号是死路。少了这条路由，
   * 一个用通行密钥注册的账号**永远**加不上登录密码。
   */
  set: '/password/set',
} as const;

/**
 * 服务端在口令这条路上发出的**稳定机器码**（响应体的 `code` 字段）。
 *
 * 这份表从 `server/src/password/service.ts` 搬来 —— 搬的理由就是上面第 2 条：
 * 客户端要按它选句子，而"服务端改了个码、客户端还在找旧串"这种漂移**不会有任何一层报错**。
 * 每条的理由跟着码走，所以下面那些注释是契约的一部分，不是服务端实现细节。
 */
export const PASSWORD_AUTH_ERROR_CODES = [
  /**
   * 账号不存在、没设口令、口令不对 —— 🔴 三者**故意同一个码同一句话**。
   *
   * 少一条，秒表或文案就变成邮箱枚举器。
   */
  'invalid_credentials',
  /**
   * 口令对了但邮箱还没验证。
   *
   * 这条路上唯一会说出账号状态的一句，所以它**只允许在校验口令通过之后**出现。
   */
  'email_not_verified',
  /**
   * 口令认证器被临时锁定（账号本身仍可用魔法链接 / 通行密钥登录）。
   *
   * 说"口令这条路被锁"而不是"账号被锁" —— 后者不属实。
   */
  'account_locked',
  /** 新口令不满足策略（太短 / 太长 / 太常见 / 已泄露，具体哪条看 `policyCode`）。 */
  'password_policy_violation',
  /** 哈希后端过载 ⇒ 503，**不降级**（服务端侧的闸门见 `server/src/password/concurrency.ts`）。
   * 报成 429 会让客户端的退避策略去惩罚一个无辜用户，而正确答案是我们降并发或扩容。 */
  'password_backend_busy',
  /**
   * 重置链接查不到 / 已过期 / 已被用过 —— 🔴 三者**故意同一个码同一句话**。
   *
   * 为什么不并进 `invalid_credentials`：那句是"凭证不对"，而这里要说的是
   * "这条路走不通，回去重新申请一封"，客户端的动作完全不同（重发链接 vs 重打口令）。
   * 为什么不区分"过期"和"从没有过"：区分它就是给攻击者一个判断哪些链接正在被广播的
   * 预言机，而合法用户两种情况的处置一模一样（回去重新申请一封）。
   */
  'invalid_reset_link',
  /**
   * 这个账号**从来没有设过口令**（纯通行密钥 / 魔法链接账号）。
   *
   * 🔴 不并进 `invalid_reset_link`：两者让客户端做的事正好相反 ——
   * 一个"回去重新点一次链接"，一个"去走「设置登录密码」把口令设上"。
   * 共用一个码就等于在一半人面前说错话。
   *
   * ⚠️ 旧版本这里写的是"去走「忘记密码」" —— 那是一句**做不到的指引**：
   * `requestPasswordReset` 对没有口令认证器的账号根本不发信。
   *
   * 它可以单独存在（不违反 anti-enumeration）是因为它**只出现在已认证的接口**上
   *（改密 / 设密），调用者手上已经有一枚有效令牌。未认证的登录那条**没有**这个码 ——
   * "没设口令"与"口令错"在那儿仍是同一句话 + 同一次哑校验。
   */
  'no_password_set',
  /**
   * 这个账号**已经有**登录口令 ⇒ 该走 `change`（要验当前口令），不是 `set`。
   *
   * 与上一条互为反面，同样**只在已认证接口**上出现，所以不构成枚举面。
   * 为什么不并成"这条路不许走"（403 一句通用话）：客户端在两种情况下要摆的界面
   * 完全不同 —— 一个是"设一个密码"的表单，一个是"当前密码 + 新密码"的表单。
   */
  'password_already_set',
] as const;

export type PasswordAuthErrorCode = (typeof PASSWORD_AUTH_ERROR_CODES)[number];

/**
 * `password_policy_violation` 的**下一层**判别：具体哪条规则拒了。
 *
 * 为什么要分两层：状态码与 `code` 在四种拒绝上完全相同（都是 400 +
 * `password_policy_violation`），但用户的动作四种都不同（加长度 / 换一句 /
 * 这句已经在泄露库里）。只说"口令不符合要求"而不给动作，等于没说。
 */
export const PASSWORD_POLICY_CODES = [
  /** 少于 {@link AUTH_PASSWORD_MIN_CODE_POINTS} 个码点。 */
  'too_short',
  /** 多于 {@link AUTH_PASSWORD_MAX_CODE_POINTS} 个码点。 */
  'too_long',
  /** 整串命中本地常见口令表。 */
  'too_common',
  /** HIBP k-匿名范围查询命中（且真送达了答复 —— 查不成是 fail-open）。 */
  'breached',
] as const;

export type PasswordPolicyCode = (typeof PASSWORD_POLICY_CODES)[number];

/**
 * 长度下限。**产品负责人 2026-10-01 拍板 = 8 个字符。**
 *
 * 🔴 这是对 NIST SP 800-63B Rev 4 的**有意偏离**：单因子口令的要求是 SHALL ≥15，
 * 8 只在对口令加盐（即多因子）时成立。偏离成立的前提是三道补偿控制必须存在
 * （本地常见口令表、HIBP 泄露检查、账号级失败锁定），缺一即打回。
 * 理由与措辞见 `docs/adr/0040-*.md`，**不许**把产品描述成"符合 NIST 800-63B"。
 */
export const AUTH_PASSWORD_MIN_CODE_POINTS = 8;

/**
 * 长度上限，按**码点**算（不是 UTF-16 单元）。
 *
 * 256 足够容纳 passphrase，同时挡住"拿 10 MB 字符串来哈希" —— Argon2 对输入长度
 * 不敏感，但内存、日志与 HTTP 体敏感。
 */
export const AUTH_PASSWORD_MAX_CODE_POINTS = 256;
