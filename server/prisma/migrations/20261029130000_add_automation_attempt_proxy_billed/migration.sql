-- A4（工单 §3 A4 / §6 第 3 格）：一次物理托管调用只扣一次额度。
--
-- 托管档的自动收集在**同一次物理调用**上碰得到两个扣点：宿主那一步的 `reserve`
-- 已经为这次尝试消费了周期额度，随后它打出的 `/api/ai/managed/chat` 又扣一次。
-- 修法取「预留那一侧记为权威」：代理侧在扣费前先**原子认领**一枚"刚刚预留过、
-- 还没被任何一次物理调用认领"的 managed 尝试，领到就跳过扣费。本列就是那枚认领标记。
--
-- 形状纪律（AGENTS §3.3）：**可空、无默认、无索引** ⇒ 元数据级变更，不产生写窗口，
-- 也不会让既有行在 hydration 时炸。老行是 NULL = "从没被认领过"，语义正好。
