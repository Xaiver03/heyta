-- 自动收集的「接收即抽取」那一档：给规则加一枚**可空**布尔（ADR-0077）。
--
-- 为什么是一列布尔、而不是一个模式字符串：
--   这一档只有两个取值 —— 抽取在哪台机器上做（设备 / 我们这台服务器）。
--   写成 `TEXT` 模式串是为了"以后可能有第三种"，而第三种今天没有任何需求方；
--   一个没人读的枚举值比一个布尔更难删（工单 A7 那条"模式写错 ⇒ 500"就是这类
--   字符串模式的实际代价：写错的那个值没人能提前发现）。
--
-- 为什么**可空**而不是 `DEFAULT false`（AGENTS.md §3.3）：
--   1. 加 NOT NULL/DEFAULT 会让这条 ALTER 在既有行上做实事，而 `automation_rules`
--      在接收路径的热读里（每一发 webhook 都要按它判一次走哪条腿）。
--   2. `NULL` 是一个**要被读出来的状态**：这一列存在之前落的规则，抽取本来就归设备，
--      把"从来没被问过"回填成"明确选了设备"是在替用户造一次他没做过的选择。
--      读面一律 `row.hostedExtraction === true`，只有显式 true 才开这条腿。
--
-- 不加索引：这一列只被"按 id 取那一行规则"顺带读出，没有任何查询以它为谓词。
ALTER TABLE "automation_rules" ADD COLUMN IF NOT EXISTS "hosted_extraction" BOOLEAN;
