/**
 * 签名令牌的**存储形态**：库里只存 `SHA-256(token)` 的十六进制，不存发出去的那句话。
 *
 * ## 为什么这一列以前是明文，以及现在为什么必须不是
 *
 * 这四列（`verificationToken` / `loginToken` / `passkeyRecoveryToken` /
 * `resetPasswordToken`）与 `PendingPasskeyRegistration.verificationToken` 存的都不是
 * "口令"，而是**能力的凭证**：拿到字符串就等于拿到"验证这个邮箱"或"登录这个账号"。
 * 存明文意味着**一次数据库泄露 = 一批还在有效期内的登录链接**。
 * 而数据库的泄露面比应用大得多（备份、只读副本、误提交的导出、库的审计日志），
 * 所以这一刀改的是"谁泄露"，不只是"泄露了什么"。
 *
 * ## 为什么是 SHA-256 而不是 Argon2id（与口令那一侧刻意不同）
 *
 * 口令是**人选的**，熵极低，所以防的是"拿到库之后离线穷举" ⇒ 必须慢（Argon2id，
 * 见 `password/hash.ts` 与 OWASP 参数下限）。
 * 令牌是 `randomBytes(32)` —— **256 位均匀熵**，离线穷举在物理上不可能，
 * 慢哈希在这里**一点额外安全都不买，却要付出可被 DoS 的算力**。
 * 所以用一次 SHA-256：它要挡的从来不是穷举，而是"读到这一列的人直接拿这一列当凭证用"。
 *
 * 判据是**取的是哪一种攻击**，不是"哪个哈希更高级"。把两条路写成一样反而是错的：
 * 令牌校验在每次点击链接时都要跑，用 Argon2 会让自己的认证路径重新撞上
 * `password/concurrency.ts` 专门躲开的那堵墙。
 *
 * ⚠️ 顺带一条**别照着这里改**的边界：如果将来某条令牌的熵不是 CSPRNG 给的
 * （比如人自己抄的 6 位恢复码、或手机号后四位 + 生日），这一列**不能只存 SHA-256** ——
 * 低熵 + 快哈希 = 库里那份能当场穷举出来。那种令牌要限次 + 短 TTL，而不是换哈希算法。
 */
import { createHash } from 'crypto';

/**
 * 把发出去的令牌转成落库/查询用的形态。
 *
 * 🔴 **必须在写和读的两边都过这一个函数**。少包一次的症状不是报错，而是"这条链接永远无效" ——
 * 库里存了明文而查询按哈希找（或反过来），用户看到的是点了邮件链接说链接已过期。
 * 这也是它不出现在各调用点、而是单独成一个模块的理由。
 */
export const hashToken = (token: string): string =>
  createHash('sha256').update(token, 'utf8').digest('hex');
